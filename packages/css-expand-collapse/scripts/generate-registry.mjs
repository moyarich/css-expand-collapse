import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const shorthandsDirectory = fileURLToPath(
  new URL("../src/registry/shorthands/", import.meta.url),
);
const indexPath = fileURLToPath(
  new URL("../src/registry/shorthands/index.ts", import.meta.url),
);

const files = (await readdir(shorthandsDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith(".ts") && entry.name !== "index.ts")
  .map((entry) => entry.name)
  .sort();

const imports = files.map((file, index) => {
  const moduleName = file.replace(/\.ts$/, ".js");
  return `import shorthand${index} from "./${moduleName}";`;
});

const entries = files.map((file, index) => {
  const property = file.replace(/\.ts$/, "");
  return `  ${JSON.stringify(property)}: shorthand${index},`;
});

const output = [
  "// Generated by scripts/generate-registry.mjs. Do not edit manually.",
  'import type { ShorthandDefinition } from "../types.js";',
  "",
  ...imports,
  "",
  "export const SHORTHANDS = {",
  ...entries,
  "} as const satisfies Readonly<Record<string, ShorthandDefinition | null>>;",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(indexPath, "utf8");
  if (current !== output) {
    console.error("Shorthand registry is out of date. Run npm run generate:registry.");
    process.exitCode = 1;
  }
} else {
  await writeFile(indexPath, output, "utf8");
  console.log(`Generated registry for ${files.length} shorthand modules.`);
}
